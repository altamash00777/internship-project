
import { useState } from "react";
import { submitEvaluation } from "../services/evaluationApi";
import "./EvaluationForm.css";

function EvaluationForm() {
  const [question, setQuestion] = useState("");
  const [answer, setAnswer] = useState("");
  const [reference, setReference] = useState("");

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);

  const handleSubmit = async (event) => {
    event.preventDefault();

    setError("");
    setResult(null);

    if (!question.trim() || !answer.trim()) {
      setError("Please enter both the question and generated answer.");
      return;
    }

    setLoading(true);

    try {
      const data = await submitEvaluation({
        question: question.trim(),
        answer: answer.trim(),
        reference: reference.trim() || null,
      });

      setResult(data);
    } catch (err) {
      setError(
        err.response?.data?.detail
          ? JSON.stringify(err.response.data.detail)
          : err.code === "ECONNABORTED"
            ? "The request timed out. Please try again."
            : "Unable to connect to the backend. Check that FastAPI is running."
      );
    } finally {
      setLoading(false);
    }
  };

  return (
    <main className="evaluation-page">
      <section className="evaluation-card">
        <div className="eyebrow">AI QUALITY LAB</div>

        <h1>AI Response Quality Evaluator</h1>

        <p className="subtitle">
          Evaluate AI-generated answers for relevance, accuracy,
          hallucinations, and completeness.
        </p>

        <form onSubmit={handleSubmit}>
          <div className="form-field">
            <label htmlFor="question">Your question *</label>
            <textarea
              id="question"
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="e.g. What is machine learning?"
              rows={3}
              maxLength={10000}
              required
              disabled={loading}
            />
          </div>

          <div className="form-field">
            <label htmlFor="answer">AI-generated answer *</label>
            <textarea
              id="answer"
              value={answer}
              onChange={(e) => setAnswer(e.target.value)}
              placeholder="Paste the answer generated by an AI..."
              rows={5}
              maxLength={30000}
              required
              disabled={loading}
            />
          </div>

          <div className="form-field">
            <label htmlFor="reference">
              Reference answer (optional)
            </label>
            <textarea
              id="reference"
              value={reference}
              onChange={(e) => setReference(e.target.value)}
              placeholder="Provide trusted facts or a reference answer..."
              rows={4}
              maxLength={30000}
              disabled={loading}
            />
            <small>
              A reference helps us verify claims against trusted information.
            </small>
          </div>

          {error && (
            <div className="message error-message" role="alert">
              {error}
            </div>
          )}

          <button
            type="submit"
            disabled={loading}
            className="evaluate-button"
          >
            {loading ? "Submitting..." : "Submit for Evaluation"}
          </button>
        </form>

        {result && (
          <section className="result-panel" aria-live="polite">
            <h2>Backend Response</h2>

            <div className="status-row">
              <span>Status</span>
              <strong>{result.status}</strong>
            </div>

            <div className="status-row">
              <span>Reference provided</span>
              <strong>
                {result.reference_provided ? "Yes" : "No"}
              </strong>
            </div>

            <div className="status-row">
              <span>Answer length</span>
              <strong>{result.answer_length} characters</strong>
            </div>

            <p>{result.message}</p>
            <small>
              This is a connection test, not a quality evaluation yet.
            </small>
          </section>
        )}
      </section>
    </main>
  );
}

export default EvaluationForm;
